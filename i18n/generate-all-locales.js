const allLangs = [
  'en', 'ar', 'hi', 'ml', 'fr', 'es', 'de', 'zh', 'ja', 'ur', 'tr', 'ru',
  'ko', 'pt', 'it', 'nl', 'bn', 'ta', 'te', 'kn', 'mr', 'gu', 'pa', 'id',
  'th', 'vi', 'pl', 'sv', 'no', 'da', 'fi', 'el', 'he', 'fa'
];

const targetDirs = [
  path.join(__dirname), // client/i18n
  path.join(__dirname, '..', '..', 'global-web', 'public', 'locales'),
  path.join(__dirname, '..', '..', 'admin', 'src', 'locales')
];

targetDirs.forEach(dir => {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
});

allLangs.forEach(lang => {
  let langDict = {};
  if (lang === 'en') {
    langDict = enData;
  } else {
    // Try to load existing file if available
    const existingFile = path.join(__dirname, `${lang}.json`);
    if (fs.existsSync(existingFile)) {
      try {
        langDict = JSON.parse(fs.readFileSync(existingFile, 'utf8'));
      } catch (e) {
        langDict = {};
      }
    }

    // Merge with master English key structure
    const customMap = translationsMap[lang] || {};
    Object.keys(enData).forEach(key => {
      if (langDict[key]) return; // Keep existing translated string if present
      if (customMap[key]) {
        langDict[key] = customMap[key];
      } else {
        // High quality fallback keeping English structure
        langDict[key] = enData[key];
      }
    });
  }

  // Write to all target directories
  targetDirs.forEach(dir => {
    const targetFile = path.join(dir, `${lang}.json`);
    fs.writeFileSync(targetFile, JSON.stringify(langDict, null, 2), 'utf8');
  });
});

