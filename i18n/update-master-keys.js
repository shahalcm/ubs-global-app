// Target directories
const targetDirs = [
  path.join(__dirname), // client/i18n
  path.join(__dirname, '..', '..', 'global-web', 'public', 'locales'),
  path.join(__dirname, '..', '..', 'admin', 'src', 'locales')
];

const allLangs = [
  'en', 'ar', 'hi', 'ml', 'fr', 'es', 'de', 'zh', 'ja', 'ur', 'tr', 'ru',
  'ko', 'pt', 'it', 'nl', 'bn', 'ta', 'te', 'kn', 'mr', 'gu', 'pa', 'id',
  'th', 'vi', 'pl', 'sv', 'no', 'da', 'fi', 'el', 'he', 'fa'
];

targetDirs.forEach(dir => {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

  allLangs.forEach(lang => {
    const langFile = path.join(dir, `${lang}.json`);
    let dict = {};
    if (fs.existsSync(langFile)) {
      try {
        dict = JSON.parse(fs.readFileSync(langFile, 'utf8'));
      } catch (e) {}
    }

    if (lang === 'en') {
      dict = sortedEn;
    } else {
      const customLangMap = translationsData[lang] || {};
      Object.keys(sortedEn).forEach(key => {
        if (!dict[key] || dict[key] === key) {
          if (customLangMap[key]) {
            dict[key] = customLangMap[key];
          } else {
            dict[key] = sortedEn[key];
          }
        }
      });
    }

    const sortedDict = {};
    Object.keys(dict).sort().forEach(k => {
      sortedDict[k] = dict[k];
    });

    fs.writeFileSync(langFile, JSON.stringify(sortedDict, null, 2), 'utf8');
  });
});

